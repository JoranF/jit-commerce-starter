const updateStoreCurrencies = createWorkflow(
  "update-store-currencies",
  (input: {
    supported_currencies: { currency_code: string; is_default?: boolean }[];
    store_id: string;
  }) => {
    const normalizedInput = transform({ input }, (data) => {
      return {
        selector: { id: data.input.store_id },
        update: {
          supported_currencies: data.input.supported_currencies.map(
            (currency) => {
              return {
                currency_code: currency.currency_code,
                is_default: currency.is_default ?? false,
              };
            }
          ),
        },
      };
    });

    const stores = updateStoresStep(normalizedInput);

    return new WorkflowResponse(stores);
  }
);

export async function setTaxInclusive(container: ExecArgs["container"], currency: string) {
  const pricing = container.resolve(Modules.PRICING);
  const existing = await pricing.listPricePreferences({
    attribute: "currency_code",
    value: currency,
  });
  if (existing.length) {
    await pricing.updatePricePreferences(
      { id: existing.map((p) => p.id) },
      { is_tax_inclusive: true }
    );
  } else {
    await pricing.createPricePreferences([
      { attribute: "currency_code", value: currency, is_tax_inclusive: true },
    ]);
  }
}

